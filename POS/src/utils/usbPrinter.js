function _buildLabelData(itemName, remarks, copyNum = 0, totalCopies = 0) {
	const now = new Date()
	const hh = String(now.getHours()).padStart(2, "0")
	const mm = String(now.getMinutes()).padStart(2, "0")
	const safe = (s) => String(s || "").replace(/"/g, "'").replace(/[\r\n]/g, " ").trim()

	const LW = 480, LH = 320
	const FW2 = 12
	const cx = (w) => Math.max(0, Math.floor((LW - w) / 2))

	const hasRemarks = !!remarks?.trim()

	// Product name: font "2" xMult=2, yMult=2 → 24px wide × 40px tall
	const itemCharW = FW2 * 2
	const itemH = 40
	const maxPerLine = Math.floor(LW / itemCharW)  // 20 chars per line

	// Word-wrap into max 2 lines
	const rawItem = safe(itemName)
	const itemLines = []
	let cur = ""
	for (const word of rawItem.split(" ")) {
		const w = word.substring(0, maxPerLine)
		if (!cur) {
			cur = w
		} else if ((cur + " " + w).length <= maxPerLine) {
			cur += " " + w
		} else {
			itemLines.push(cur)
			cur = w
			if (itemLines.length === 2) break
		}
	}
	if (cur && itemLines.length < 2) itemLines.push(cur)

	const lineGap = 4
	const remGap = 8, remH = 20

	const contentH = itemLines.length * itemH + (itemLines.length - 1) * lineGap
		+ (hasRemarks ? remGap + remH : 0)

	// Body area: below logo bottom (8+LOGO_H+8) → above time (LH-34)
	const bodyTop = 8 + LOGO_H + 8
	const bodyBottom = LH - 34
	const blockTop = Math.floor((bodyTop + bodyBottom - contentH) / 2)

	// Split into text-only commands (before and after the binary BITMAP)
	const preCmds = [
		"SIZE 60 mm,40 mm",
		"GAP 3 mm,0",
		"SPEED 3",
		"DENSITY 8",
		"DIRECTION 0,0",
		"CODEPAGE UTF-8",
		"CLS",
	]

	const postCmds = []
	itemLines.forEach((line, i) => {
		postCmds.push(`TEXT ${cx(line.length * itemCharW)},${blockTop + i * (itemH + lineGap)},"2",0,2,2,"${line}"`)
	})
	if (hasRemarks) {
		const rem = safe(remarks).substring(0, 40)
		const remY = blockTop + itemLines.length * (itemH + lineGap) - lineGap + remGap
		postCmds.push(`TEXT ${cx(rem.length * FW2)},${remY},"2",0,1,1,"${rem}"`)
	}
	postCmds.push(`TEXT 10,${LH - 30},"2",0,1,1,"${hh}:${mm}"`)
	// Copy counter bottom-right (only when printing multiple copies)
	if (totalCopies > 1) {
		const counter = `${copyNum}/${totalCopies}`
		postCmds.push(`TEXT ${LW - 10 - counter.length * FW2},${LH - 30},"2",0,1,1,"${counter}"`)
	}
	postCmds.push("PRINT 1,1")

	// BITMAP command header (binary data follows immediately, no quotes)
	const logoX = cx(LOGO_W)
	const enc = new TextEncoder()
	const parts = [
		enc.encode(preCmds.join("\r\n") + "\r\n"),
		enc.encode(`BITMAP ${logoX},8,${LOGO_BPR},${LOGO_H},0,`),
		LOGO_DATA,
		enc.encode("\r\n"),
		enc.encode(postCmds.join("\r\n") + "\r\n"),
	]

	const total = parts.reduce((s, p) => s + p.length, 0)
	const out = new Uint8Array(total)
	let off = 0
	for (const p of parts) { out.set(p, off); off += p.length }
	return out
}

export async function printLabelUSB(itemName, remarks, copies = 1) {
	await _ensureConnected(STORAGE_KEY_LABEL, _label, "label")
	for (let i = 0; i < copies; i++) {
		const data = _buildLabelData(itemName, remarks, i + 1, copies)
		await _transfer(_label, data)
		if (copies > 1 && i < copies - 1) {
			await new Promise((r) => setTimeout(r, 200))
		}
	}
}
